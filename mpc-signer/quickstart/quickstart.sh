#!/usr/bin/env bash
# Docker quick start for the MPC signer (3 nodes + coordinator on one host).
#
#   ./quickstart.sh init     build image, create secrets (.env), node identities, cluster.json
#   ./quickstart.sh up       start the cluster
#   ./quickstart.sh setup    aux info (once, a few minutes) + first key; prints the address
#   ./quickstart.sh status   keys and presignature pool
#   ./quickstart.sh newkey   create another key
#   ./quickstart.sh admin METHOD PATH [JSON]   call the coordinator admin API
#   ./quickstart.sh down     stop (keeps key shares)
#   ./quickstart.sh destroy  stop and DELETE all key shares and secrets
set -Eeuo pipefail
cd "$(dirname "$0")"
log() { printf '[quickstart] %s\n' "$*"; }
dc() { docker compose "$@"; }
rand() { head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n'; }

CHAIN_ID="${CHAIN_ID:-1337}"
MPC_BIGINT="${MPC_BIGINT:-bigint-num}"

load_env() {
  [ -f .env ] || { log "run ./quickstart.sh init first"; exit 1; }
  set -a; . ./.env; set +a
}

coord() { # METHOD PATH [BODY]
  local port="${MPC_PUBLISH:-127.0.0.1:9100}"
  curl -sS -X "$1" "http://${port}$2" \
    -H "Authorization: Bearer ${MPC_ADMIN_TOKEN}" -H 'Content-Type: application/json' ${3:+--data "$3"}
}

init() {
  if [ -f cluster.json ]; then log "already initialised (cluster.json exists)"; return; fi
  if [ ! -f .env ]; then
    umask 077
    cat > .env <<EOF
# Generated by quickstart.sh. Keep secret, never commit.
MPC_BIGINT=$MPC_BIGINT
MPC_NODE_TOKEN=$(rand)
MPC_ADMIN_TOKEN=$(rand)
MPC_NODE0_PASSPHRASE=$(rand)
MPC_NODE1_PASSPHRASE=$(rand)
MPC_NODE2_PASSPHRASE=$(rand)
# Besu JSON-RPC as seen from the coordinator container
MPC_BESU_RPC=${MPC_BESU_RPC:-http://host.docker.internal:8545}
EOF
    umask 022
  fi
  load_env
  echo '{}' > cluster.json   # placeholder so the bind mount exists
  if [ "${MPC_SKIP_BUILD:-0}" = 1 ]; then
    log "using existing image ${MPC_IMAGE:-mpc-signer:local}"
  else
    log "building image (first build compiles the Rust crypto; takes several minutes)"
    dc build node0
  fi
  local parties=""
  for i in 0 1 2; do
    pub=$(dc run --rm --no-deps -T "node$i" mpc-node init | tail -n1)
    sign_pk=$(printf '%s' "$pub" | sed -E 's/.*"sign_pk":"([0-9a-f]+)".*/\1/')
    kx_pk=$(printf '%s' "$pub" | sed -E 's/.*"kx_pk":"([0-9a-f]+)".*/\1/')
    [ -n "$parties" ] && parties="$parties,"
    parties="$parties
    {\"id\": $i, \"url\": \"http://node$i:7000\", \"sign_pk\": \"$sign_pk\", \"kx_pk\": \"$kx_pk\"}"
    log "node$i identity created"
  done
  cat > cluster.json <<EOF
{
  "threshold": 2,
  "parties": [$parties
  ],
  "policy": {
    "chain_id": $CHAIN_ID,
    "max_value_wei": "1000000000000000000000",
    "max_gas": 30000000,
    "allowed_to": [],
    "deny_contract_creation": false
  }
}
EOF
  log "wrote cluster.json (public keys only) and .env (secrets)"
}

up() {
  load_env
  dc up -d
  for _ in $(seq 1 60); do curl -sf "http://${MPC_PUBLISH:-127.0.0.1:9100}/health" >/dev/null && break; sleep 1; done
  log "coordinator: http://${MPC_PUBLISH:-127.0.0.1:9100}  (Web3Signer-compatible JSON-RPC)"
}

setup() {
  load_env
  log "aux info generation: safe primes + ZK proofs, once per cluster (a few minutes)"
  coord POST /admin/aux; echo
  if [ "$(coord GET /admin/keys)" = "[]" ]; then
    log "distributed key generation"
    coord POST /admin/keys; echo
  fi
  status
}

status() {
  load_env
  log "keys:"; coord GET /admin/keys; echo
  log "pool:"; coord GET /admin/pool; echo
}

case "${1:-}" in
  init) init ;;
  up) up ;;
  setup) setup ;;
  status) status ;;
  newkey) load_env; coord POST /admin/keys; echo ;;
  admin) load_env; shift; coord "$@"; echo ;;
  logs) dc logs -f --tail 50 ;;
  down) dc down ;;
  destroy)
    read -rp "Delete ALL key shares and secrets? Funds on MPC addresses become unrecoverable. Type 'destroy': " a
    [ "$a" = destroy ] || exit 1
    dc down -v; rm -f .env cluster.json; log "destroyed" ;;
  *) sed -n '2,13p' "$0"; exit 1 ;;
esac
