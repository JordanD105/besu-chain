#!/usr/bin/env bash
# firewalld rules for the production layout (docs/production-layout.md). Run on each host as root.
#
# By hand, with the documented addresses (192.168.68.135-.139):
#   CLIENTS="10.1.2.3 10.1.2.4" ADMIN=10.1.2.9 ./firewall-layout.sh 135      (135 136 137 138 139)
# With any IP plan (Ansible passes these from inventory.yml + settings.yml):
#   ROLE=app|node|monitoring  this host's role (app = HA pair: coordinator, proxy, HAProxy)
#   PEER=<ip>                 app only: the other HA host (VRRP)
#   HAS_MPC=1                 an MPC node runs on this host (port 7000)
#   BESU_HOSTS, MPC_HOSTS, COORDS (the HA pair), MON: space-separated IPs
#   CLIENTS  applications that call the proxy (VIP:30000) and users of chainlens (:30100)
#   ADMIN    the bastion / operator host (SSH, Grafana, MPC admin API, Remix)
#   REMIX_USERS  developers allowed to open Remix (:30200 on the monitoring host), optional
# Only the listed sources reach each port; everything else stays closed (firewalld default zone).
# Review with: firewall-cmd --list-all
#
# Ports that Docker publishes (proxy, coordinator, MPC node, Grafana, chainlens, Besu nodes without
# host networking) bypass firewalld: Docker forwards them itself. The same allow list is therefore
# also applied to forwarded (DNAT) connections in an nftables table of its own (inet besu_docker):
# listed sources only, every other new connection to a published port is dropped. Applied at boot by
# the systemd unit besu-docker-firewall. Review with: nft list table inet besu_docker
set -Eeuo pipefail
host="${1:-}"
NET=192.168.68
CLIENTS="${CLIENTS:-}"
ADMIN="${ADMIN:?set ADMIN to the bastion/operator IP}"

# defaults: the documented layout, chosen by the host number
case "$host" in
  135|136) ROLE="${ROLE:-app}";        PEER="${PEER:-$([ "$host" = 135 ] && echo "$NET.136" || echo "$NET.135")}" ;;
  137|138) ROLE="${ROLE:-node}" ;;
  139)     ROLE="${ROLE:-monitoring}" ;;
  "")      : "${ROLE:?usage: ./firewall-layout.sh 135|136|137|138|139, or set ROLE=app|node|monitoring}" ;;
  *) echo "unknown host $host" >&2; exit 1 ;;
esac
case "$host" in 135|137|138) HAS_MPC="${HAS_MPC:-1}" ;; *) HAS_MPC="${HAS_MPC:-0}" ;; esac
BESU_HOSTS="${BESU_HOSTS:-$NET.135 $NET.136 $NET.137 $NET.138}"
MPC_HOSTS="${MPC_HOSTS:-$NET.135 $NET.137 $NET.138}"      # mpc1, mpc2, mpc3
COORDS="${COORDS:-$NET.135 $NET.136}"                     # coord1, coord2 (also HAProxy, proxies)
MON="${MON:-$NET.139}"

DOCKER_RULES=()
allow() { # allow <source> <port>/<proto>
  local src=$1 port=${2%/*} proto=${2#*/}
  firewall-cmd --permanent -q --add-rich-rule="rule family=\"ipv4\" source address=\"$src\" port port=\"$port\" protocol=\"$proto\" accept"
  DOCKER_RULES+=("$proto $port $src")
}
allow_all() { local port=$1; shift; for s in "$@"; do [ -n "$s" ] && allow "$s" "$port"; done; }

allow "$ADMIN" 22/tcp
allow_all 9101/tcp $MON                                          # node-exporter

case "$ROLE" in
  app)
    : "${PEER:?set PEER to the other HA host}"
    firewall-cmd --permanent -q --add-rich-rule="rule family=\"ipv4\" source address=\"$PEER\" protocol value=\"vrrp\" accept"
    for p in 30303/tcp 30303/udp 30304/tcp 30304/udp; do allow_all "$p" $BESU_HOSTS; done   # val + rpc p2p
    allow_all 9545/tcp $MON; allow_all 9546/tcp $MON                                       # Besu metrics
    allow_all 8545/tcp $COORDS "$ADMIN"            # HAProxy on the VIP (proxies, coordinators, operator)
    allow_all 8555/tcp $COORDS $MON "$ADMIN"       # rpc node direct (HAProxy, chainlens -> rpc2, operator)
    allow_all 9100/tcp $COORDS $MPC_HOSTS $MON "$ADMIN"  # coordinator: HAProxy, MPC relay, metrics, admin
    allow_all 30000/tcp $CLIENTS $MON "$ADMIN"     # proxy (VIP and this host)
    ;;
  node)
    for p in 30303/tcp 30303/udp; do allow_all "$p" $BESU_HOSTS; done                     # validator p2p
    allow_all 9545/tcp $MON
    ;;
  monitoring)
    allow_all 3000/tcp "$ADMIN"                    # Grafana
    allow_all 30100/tcp $CLIENTS "$ADMIN"          # chainlens
    allow_all 30200/tcp "$ADMIN" ${REMIX_USERS:-}  # Remix IDE (remix/)
    ;;
  *) echo "unknown ROLE $ROLE (app, node or monitoring)" >&2; exit 1 ;;
esac
[ "$HAS_MPC" = 1 ] && allow_all 7000/tcp $COORDS                                           # MPC node
firewall-cmd --reload
echo "firewall for ${host:-$ROLE} applied:"; firewall-cmd --list-rich-rules

# ---- Docker-published ports: the same allow list for forwarded connections (see the header)
{ echo "# Generated by ha/firewall-layout.sh: <proto> <original destination port> <allowed source>"
  printf '%s\n' "${DOCKER_RULES[@]}"; } > /etc/besu-docker-firewall.rules
cat > /usr/local/sbin/besu-docker-firewall <<'APPLY'
#!/bin/bash
# Applies /etc/besu-docker-firewall.rules to connections Docker forwards to containers (installed by
# ha/firewall-layout.sh, run at boot by besu-docker-firewall.service). The rules live in their own
# nftables table (inet besu_docker): Docker and firewalld never touch it, so neither a Docker restart
# nor a firewalld reload opens a gap (Docker re-orders its own FORWARD jumps on a reload, which is why
# DOCKER-USER is not used). A drop in any table is final.
set -euo pipefail
f=$(mktemp); trap 'rm -f "$f"' EXIT
{ echo 'table inet besu_docker'
  echo 'delete table inet besu_docker'
  echo 'table inet besu_docker {'
  echo ' chain forward {'
  echo '  type filter hook forward priority -10; policy accept;'
  echo '  ct state established,related accept'
  echo '  iifname "docker*" accept'                  # from containers (outgoing, between them)
  echo '  iifname "br-*" accept'
  while read -r proto port src; do
    case "$proto" in ""|\#*) continue ;; esac
    echo "  ct status dnat meta l4proto $proto ct original proto-dst $port ip saddr $src accept"
  done < /etc/besu-docker-firewall.rules
  echo '  ct status dnat ct state new drop'           # any other new connection to a published port
  echo ' }'
  echo '}'; } > "$f"
nft -f "$f"
APPLY
chmod 755 /usr/local/sbin/besu-docker-firewall
cat > /etc/systemd/system/besu-docker-firewall.service <<'UNIT'
[Unit]
Description=besu-chain: firewall for Docker-published ports (ha/firewall-layout.sh)
After=firewalld.service nftables.service docker.service

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/usr/local/sbin/besu-docker-firewall

[Install]
WantedBy=multi-user.target
UNIT
systemctl daemon-reload
systemctl enable -q besu-docker-firewall.service
systemctl restart besu-docker-firewall.service
echo "Docker-published ports: ${#DOCKER_RULES[@]} allow rules in nftables table besu_docker, every other new connection dropped"
