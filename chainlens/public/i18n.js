function detectLocale() {
    const saved = localStorage.getItem("chainlens.lang");
    if (saved && locales[saved]) {
        return saved;
    }
    const lang = (navigator.language || "en").toLowerCase();
    return lang.startsWith("zh") ? "zh" : "en";
}

let locale = detectLocale();

function t(key, vars) {
    const table = locales[locale] || locales.en;
    let text = table[key] || locales.en[key] || key;

    if (vars) {
        for (const [name, value] of Object.entries(vars)) {
            text = text.replaceAll("{" + name + "}", String(value));
        }
    }

    return text;
}

function getLocale() {
    return locale;
}

function applyStatic() {
    document.documentElement.lang = locale === "zh" ? "zh-CN" : "en";

    for (const node of document.querySelectorAll("[data-i18n]")) {
        node.textContent = t(node.dataset.i18n);
    }

    for (const node of document.querySelectorAll("[data-i18n-placeholder]")) {
        node.placeholder = t(node.dataset.i18nPlaceholder);
    }

    for (const node of document.querySelectorAll("[data-i18n-aria]")) {
        node.setAttribute("aria-label", t(node.dataset.i18nAria));
    }
}

function setLocale(next) {
    if (!locales[next] || next === locale) {
        return;
    }

    locale = next;
    localStorage.setItem("chainlens.lang", next);
    applyStatic();
    document.dispatchEvent(new Event("localechange"));
}

applyStatic();

const langSelect = document.querySelector("#lang");

if (langSelect) {
    langSelect.value = locale;
    langSelect.addEventListener("change", () => setLocale(langSelect.value));
}
